// Regenerates src/errorCodeTable.ts from the compiled device manager bundle of Creality Print.
// Run after a Creality Print update replaces resources/web/deviceMgr/assets/*.js:
//   node scripts/extract-error-codes.mjs <path to the deviceMgr bundle that defines errorJson> src/errorCodeTable.ts
// The bundle is only read. The two object literals (errorJson: code, level, models; printerCode:
// English text) are checked to contain data only, then evaluated in an empty VM context. Duplicate
// keys keep the last value, exactly like the web page does.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const [bundlePath, outPath] = process.argv.slice(2);
if (!bundlePath || !outPath) throw new Error('usage: node extract-error-codes.mjs <bundle.js> <out.ts>');
const src = readFileSync(bundlePath, 'utf8');
const BS = String.fromCharCode(92);

function literalAfter(marker) {
  const start = src.indexOf(marker);
  if (start < 0) throw new Error(`${marker} not found in the bundle`);
  const begin = src.indexOf('{', start);
  let depth = 0, inString = false;
  for (let j = begin; j < src.length; j++) {
    const c = src[j];
    if (inString) { if (c === BS) j++; else if (c === '"') inString = false; continue; }
    if (c === '"') inString = true;
    else if (c === '{') depth++;
    else if (c === '}') { depth--; if (depth === 0) return src.slice(begin, j + 1); }
  }
  throw new Error(`unterminated ${marker}`);
}

function evalData(literal) {
  const withoutStrings = literal.replace(/"(?:[^"\\]|\\.)*"/g, '""');
  if (/[()=;`]|function/.test(withoutStrings)) throw new Error('the literal contains code, refusing to evaluate it');
  return vm.runInNewContext(`(${literal})`, Object.create(null), { timeout: 1000 });
}

const errorJson = evalData(literalAfter('const errorJson='));
const printerCode = evalData(literalAfter('printerCode='));
const rows = Object.entries(errorJson).map(([key, entry]) => [
  /^\d+$/.test(key) ? Number(key) : key,
  String(entry.code ?? ''),
  Number(entry.level ?? 0),
  Array.isArray(entry.apply) ? entry.apply.map(String) : [],
  String(printerCode[key] ?? 'Unknown error').replace(/&quot;/g, '"').replace(/，/g, ', '),
]);

const header = `// GENERATED by scripts/extract-error-codes.mjs from resources/web/deviceMgr/assets (errorJson + printerCode).
// Do not edit by hand: Italian texts live in errorCodes.ts.
// Row: [lookup key, display code, level, printer models, English text]. ${rows.length} entries.
export type ErrorRow = readonly [key: number | string, code: string, level: number, apply: readonly string[], en: string];

export const errorCodeTable: readonly ErrorRow[] = [
`;
const body = rows.map((row) => `  ${JSON.stringify(row)},`).join('\n');
writeFileSync(outPath, `${header}${body}\n];\n`);
console.error(`wrote ${rows.length} entries to ${outPath}`);
