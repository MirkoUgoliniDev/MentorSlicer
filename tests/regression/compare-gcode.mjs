#!/usr/bin/env node
// Compares two G-code files (or two folders of them) after masking the lines that change from run
// to run or from phase to phase (doc/specs/F0-baseline-verifica-spec.md, section 3).
//
//   node tests/regression/compare-gcode.mjs <baseline.gcode[.gz]> <candidate.gcode[.gz]> [options]
//   node tests/regression/compare-gcode.mjs --baseline-dir <dir> --candidate-dir <dir> [options]
//   node tests/regression/compare-gcode.mjs --hash <file.gcode[.gz]> [<file> ...]
//
// options:
//   --masks <file>            extra rules (default: tests/regression/masks.json when present)
//   --phase <Fn>              also apply the phase_rules of every phase up to <Fn>
//   --strict                  disable soft rules (profile_version); EXTRA files become errors
//   --max-diffs <n>           differing lines shown per file (default 20)
//   --context <n>             context lines around each shown difference (default 2)
//   --write-normalized <dir>  write <name>.norm.gcode for inspection
//   --hash                    print only "<sha256>  <file>" of the normalised content
//   --json                    machine-readable summary on stdout instead of text
//
// Exit codes: 0 all IDENTICAL; 1 at least one DIFFERENT; 2 usage error; 3 input unreadable or
// MISSING (and EXTRA with --strict). 3 wins over 1.
//
// Module use: import { normalize, compareFiles, loadRules, sha256 } from './compare-gcode.mjs'.
// Node 20+, no dependencies.

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { gunzipSync } from 'node:zlib';

const here = dirname(fileURLToPath(import.meta.url));
export const DEFAULT_MASKS = join(here, 'masks.json');

// Built-in line rules (section 3.1). masks.json replaces a rule with the same id and appends the others.
export const BUILTIN_RULES = [
  { id: 'generated_by', pattern: '^; generated by .+ on .+$', replace: '; generated by <APP> on <TIMESTAMP>', expect: 'once' },
  { id: 'creality_uuid', pattern: '^; creality_uuid: .*$', replace: '; creality_uuid: <UUID>', expect: 'once' },
  { id: 'task_id_pending', pattern: '^; creality_task_id_pending: .*$', replace: null },
  { id: 'task_id', pattern: '^; creality_task_id: .*$', replace: null },
  { id: 'profile_version', pattern: '^; profile_version: .*$', replace: null, soft: true },
  { id: 'fixture_marker', pattern: '^; PRINT_ADVISOR_FIXTURE: .*$', replace: null },
];

const PHASES = ['F0', 'F1', 'F2', 'F3', 'F4', 'F5', 'F6', 'F7', 'F8'];

export function sha256(text) {
  return createHash('sha256').update(text, 'latin1').digest('hex');
}

// Reads a G-code file (gzipped or not) as latin1 so every byte round-trips.
export function readGcode(file) {
  const buf = readFileSync(file);
  const data = file.toLowerCase().endsWith('.gz') || (buf[0] === 0x1f && buf[1] === 0x8b) ? gunzipSync(buf) : buf;
  return data.toString('latin1');
}

// Loads the rules: built-ins, then masks.json (same id = replacement), then phase_rules up to `phase`.
// `strict` removes the soft rules.
export function loadRules({ masks = DEFAULT_MASKS, phase = null, strict = false } = {}) {
  const byId = new Map(BUILTIN_RULES.map((r) => [r.id, { ...r }]));
  const warnings = [];
  if (masks && existsSync(masks)) {
    const json = JSON.parse(readFileSync(masks, 'utf8'));
    for (const r of json.rules ?? []) byId.set(r.id, { ...r });
    if (phase) {
      const idx = PHASES.indexOf(phase);
      if (idx < 0) throw new Error(`unknown phase ${phase} (expected F0..F8)`);
      for (const p of PHASES.slice(0, idx + 1)) {
        for (const r of json.phase_rules?.[p] ?? []) {
          if (!r.why) warnings.push(`phase rule ${p}/${r.id} has no "why"`);
          byId.set(r.id, { ...r, phase: p });
        }
      }
    }
  } else if (masks && masks !== DEFAULT_MASKS) {
    throw new Error(`masks file not found: ${masks}`);
  }
  let rules = [...byId.values()];
  if (strict) rules = rules.filter((r) => !r.soft);
  for (const r of rules) {
    if (typeof r.pattern !== 'string') throw new Error(`rule ${r.id}: pattern must be a string`);
    r.re = new RegExp(r.pattern);
  }
  return { rules, warnings };
}

const BIGTREE_HEADER = /^;[0-9a-fA-F]{8}\r?$/;

// Normalises a G-code text: line split, thumbnail block filter, line rules. Returns the lines, the
// per-rule match counts and the masked content hash.
export function normalize(text, rules) {
  const raw = text.split(/\r?\n/);
  if (raw.length && raw[raw.length - 1] === '') raw.pop();
  const counts = {};
  for (const r of rules) counts[r.id] = 0;
  counts.thumbnail_block = 0;
  counts.thumbnail_inline = 0;
  const lines = [];
  let skip = null; // 'block' | 'bigtree'
  // The thumbnail writers end with "\n\n" (Thumbnails.hpp), so one blank line right after a dropped
  // block or inline image is dropped too: a file without thumbnails has no blank line there.
  let dropBlank = false;
  // The bigtree thumbnail header (8 hex digits) is only honoured before the executable block, and only
  // when its end marker exists: otherwise an 8-hex-digit comment in the body would swallow the rest.
  const hasBigtreeEnd = raw.some((l) => l.startsWith('; bigtree thumbnail end'));
  let inBody = false;
  for (const line of raw) {
    if (skip === 'block') { if (line.startsWith('; THUMBNAIL_BLOCK_END')) { skip = null; dropBlank = true; } continue; }
    if (skip === 'bigtree') { if (line.startsWith('; bigtree thumbnail end')) { skip = null; dropBlank = true; } continue; }
    if (dropBlank) { dropBlank = false; if (line === '') continue; }
    if (line.startsWith('; THUMBNAIL_BLOCK_START')) { skip = 'block'; counts.thumbnail_block++; continue; }
    if (line.startsWith('; EXECUTABLE_BLOCK_START')) inBody = true;
    if (!inBody && hasBigtreeEnd && BIGTREE_HEADER.test(line)) { skip = 'bigtree'; counts.thumbnail_inline++; continue; }
    if (line.startsWith(';gimage:') || line.startsWith(';simage:')) { counts.thumbnail_inline++; dropBlank = true; continue; }
    let out = line;
    for (const r of rules) {
      if (r.re.test(line)) {
        counts[r.id]++;
        out = r.replace === null || r.replace === undefined ? null : r.replace;
        break;
      }
    }
    if (out !== null) lines.push(out);
  }
  const hash = sha256(lines.join('\n'));
  const warnings = [];
  for (const r of rules) {
    if (r.expect === 'once' && counts[r.id] !== 1)
      warnings.push(`rule ${r.id} matched ${counts[r.id]} times, expected once (header format changed?)`);
  }
  return { lines, counts, hash, warnings };
}

// Parses "; key = value" lines inside the CONFIG block.
export function parseConfig(lines) {
  const cfg = new Map();
  const start = lines.indexOf('; CONFIG_BLOCK_START');
  if (start < 0) return cfg;
  for (let i = start + 1; i < lines.length && !lines[i].startsWith('; CONFIG_BLOCK_END'); ++i) {
    const m = /^; ([A-Za-z0-9_]+) = (.*)$/.exec(lines[i]);
    if (m) cfg.set(m[1], m[2]);
  }
  return cfg;
}

const trunc = (v, n = 120) => (v.length > n ? `${v.slice(0, n)}...` : v);

export function configDiff(a, b) {
  const ca = parseConfig(a), cb = parseConfig(b);
  const added = [], removed = [], changed = [];
  for (const [k, v] of cb) if (!ca.has(k)) added.push({ key: k, value: trunc(v) });
  for (const [k, v] of ca) {
    if (!cb.has(k)) removed.push({ key: k, value: trunc(v) });
    else if (cb.get(k) !== v) changed.push({ key: k, from: trunc(v), to: trunc(cb.get(k)) });
  }
  return { added, removed, changed };
}

// Tracks the section, layer, z, TYPE and object while scanning a line array.
class Locator {
  constructor() { this.section = 'HEADER'; this.layer = 0; this.z = null; this.type = null; this.object = null; }
  feed(line) {
    if (line.startsWith('; HEADER_BLOCK_END')) this.section = 'PREAMBLE';
    else if (line.startsWith('; EXECUTABLE_BLOCK_START')) this.section = 'EXECUTABLE';
    else if (line.startsWith('; EXECUTABLE_BLOCK_END')) this.section = 'FOOTER';
    else if (line.startsWith('; CONFIG_BLOCK_START')) this.section = 'CONFIG';
    else if (line.startsWith('; CONFIG_BLOCK_END')) this.section = 'FOOTER';
    else if (this.section === 'EXECUTABLE') {
      if (line.startsWith(';LAYER_CHANGE')) this.layer++;
      else if (line.startsWith(';Z:')) this.z = line.slice(3).trim();
      else if (line.startsWith(';TYPE:')) this.type = line.slice(6).trim();
      else if (line.startsWith('; printing object ')) this.object = line.slice(18).trim();
    }
  }
  describe() {
    let s = this.section;
    if (this.section === 'EXECUTABLE') {
      s += ` layer ${this.layer}`;
      if (this.z !== null) s += ` z=${this.z}`;
      if (this.type) s += ` TYPE ${this.type}`;
      if (this.object) s += ` object ${this.object}`;
    }
    return s;
  }
}

// Compares two normalised line arrays. Returns the differences to show (not a full LCS diff).
export function compareLines(a, b, { maxDiffs = 20, context = 2 } = {}) {
  const res = { sameLength: a.length === b.length, linesA: a.length, linesB: b.length, differing: 0, shown: [] };
  const loc = new Locator();
  const n = Math.min(a.length, b.length);
  for (let i = 0; i < n; ++i) {
    loc.feed(a[i]);
    if (a[i] === b[i]) continue;
    res.differing++;
    if (res.shown.length < maxDiffs) {
      res.shown.push({
        line: i + 1, where: loc.describe(), a: a[i], b: b[i],
        before: a.slice(Math.max(0, i - context), i), after: a.slice(i + 1, i + 1 + context),
      });
    }
    if (!res.sameLength) break; // show only the first divergence when the lengths differ
  }
  if (res.sameLength === false && res.differing === 0) {
    // one file is a prefix of the other
    for (let i = n; i < Math.max(a.length, b.length) && i < n + 1; ++i) {
      res.differing++;
      res.shown.push({ line: n + 1, where: loc.describe(), a: a[n] ?? '<end of file>', b: b[n] ?? '<end of file>', before: [], after: [] });
    }
  }
  return res;
}

// Compares two files. Returns { status, ... } with status IDENTICAL | DIFFERENT | ERROR.
export function compareFiles(fileA, fileB, opts = {}) {
  const name = opts.name ?? basename(fileA).replace(/\.gz$/i, '').replace(/\.gcode$/i, '');
  const { rules, warnings: ruleWarnings } = opts.rulesLoaded ?? loadRules(opts);
  let textA, textB;
  try { textA = readGcode(fileA); } catch (e) { return { name, status: 'ERROR', error: `cannot read ${fileA}: ${e.message}` }; }
  try { textB = readGcode(fileB); } catch (e) { return { name, status: 'ERROR', error: `cannot read ${fileB}: ${e.message}` }; }
  const na = normalize(textA, rules), nb = normalize(textB, rules);
  const warnings = [...ruleWarnings, ...na.warnings.map((w) => `baseline: ${w}`), ...nb.warnings.map((w) => `candidate: ${w}`)];
  if (opts.writeNormalized) {
    mkdirSync(opts.writeNormalized, { recursive: true });
    writeFileSync(join(opts.writeNormalized, `${name}.baseline.norm.gcode`), na.lines.join('\n') + '\n', 'latin1');
    writeFileSync(join(opts.writeNormalized, `${name}.candidate.norm.gcode`), nb.lines.join('\n') + '\n', 'latin1');
  }
  const masked = Object.fromEntries(Object.entries(na.counts).filter(([, v]) => v > 0));
  if (na.hash === nb.hash) return { name, status: 'IDENTICAL', sha256: na.hash, lines: na.lines.length, masked, warnings };
  const diff = compareLines(na.lines, nb.lines, opts);
  return { name, status: 'DIFFERENT', sha256_baseline: na.hash, sha256_candidate: nb.hash, lines: na.lines.length, masked, warnings, diff, config: configDiff(na.lines, nb.lines) };
}

// ---- directory pairing ----

function gcodeFiles(dir) {
  const out = new Map();
  for (const f of readdirSync(dir)) {
    if (!/\.gcode(\.gz)?$/i.test(f)) continue;
    if (!statSync(join(dir, f)).isFile()) continue;
    const key = f.replace(/\.gz$/i, '').replace(/\.gcode$/i, '');
    const plain = !f.toLowerCase().endsWith('.gz');
    if (!out.has(key) || plain) out.set(key, join(dir, f)); // a plain file wins over its .gz twin
  }
  return out;
}

export function compareDirs(baseDir, candDir, opts = {}) {
  const base = gcodeFiles(baseDir), cand = gcodeFiles(candDir);
  const results = [];
  for (const [name, file] of [...base].sort()) {
    if (!cand.has(name)) results.push({ name, status: 'MISSING', error: 'candidate not found' });
    else results.push(compareFiles(file, cand.get(name), { ...opts, name }));
  }
  for (const [name] of [...cand].sort()) if (!base.has(name)) results.push({ name, status: 'EXTRA', error: 'no baseline for this file' });
  return results;
}

// ---- text output ----

function printResult(r, opts) {
  const pad = (s) => s.padEnd(Math.max(14, opts.nameWidth ?? 14));
  const maskedText = (m) => Object.entries(m ?? {}).map(([k, v]) => `${k}=${v}`).join(' ');
  if (r.status === 'IDENTICAL') {
    console.log(`== ${pad(r.name)} IDENTICAL  sha256 ${r.sha256.slice(0, 12)}  ${r.lines} lines  masked: ${maskedText(r.masked) || '-'}`);
  } else if (r.status === 'DIFFERENT') {
    const d = r.diff;
    const first = d.shown[0];
    const head = d.sameLength
      ? `${d.differing} of ${d.linesA} lines differ`
      : `line counts differ (baseline ${d.linesA}, candidate ${d.linesB})`;
    console.log(`== ${pad(r.name)} DIFFERENT  ${head}${first ? ` (first: line ${first.line}, ${first.where})` : ''}`);
    for (const s of d.shown) {
      for (const [i, c] of s.before.entries()) console.log(`     ${s.line - s.before.length + i}: ${c}`);
      console.log(`   - ${s.line}: ${s.a}`);
      console.log(`   + ${s.line}: ${s.b}`);
      for (const [i, c] of s.after.entries()) console.log(`     ${s.line + 1 + i}: ${c}`);
    }
    if (d.sameLength && d.differing > d.shown.length) console.log(`   ... ${d.differing - d.shown.length} more differing lines`);
    const c = r.config;
    for (const x of c.added) console.log(`   CONFIG: added ${x.key}: ${x.value}`);
    for (const x of c.removed) console.log(`   CONFIG: removed ${x.key}: ${x.value}`);
    for (const x of c.changed) console.log(`   CONFIG: changed ${x.key}: ${x.from} -> ${x.to}`);
    if (!c.added.length && !c.removed.length && !c.changed.length) console.log('   CONFIG: no key differences');
  } else {
    console.log(`== ${pad(r.name)} ${r.status.padEnd(9)}  ${r.error}`);
  }
  for (const w of r.warnings ?? []) console.log(`   WARN ${w}`);
}

export function summarize(results, { strict = false } = {}) {
  const count = (s) => results.filter((r) => r.status === s).length;
  const s = { identical: count('IDENTICAL'), different: count('DIFFERENT'), missing: count('MISSING'), extra: count('EXTRA'), error: count('ERROR'),
    warnings: results.reduce((n, r) => n + (r.warnings?.length ?? 0), 0) };
  let exit = 0;
  if (s.different) exit = 1;
  if (s.missing || s.error || (strict && s.extra)) exit = 3;
  return { ...s, exit };
}

// ---- CLI ----

function usage(msg) {
  if (msg) console.error(`error: ${msg}`);
  console.error('usage: compare-gcode.mjs <baseline> <candidate> | --baseline-dir <dir> --candidate-dir <dir> | --hash <file...>');
  console.error('       [--masks <file>] [--phase Fn] [--strict] [--max-diffs n] [--context n] [--write-normalized <dir>] [--json]');
  process.exit(2);
}

function main(argv) {
  const o = { files: [], masks: DEFAULT_MASKS, phase: null, strict: false, maxDiffs: 20, context: 2, writeNormalized: null, hash: false, json: false };
  const value = (i, a) => { if (argv[i] === undefined || argv[i].startsWith('--')) usage(`${a} needs a value`); return argv[i]; };
  for (let i = 0; i < argv.length; ++i) {
    const a = argv[i];
    if (a === '--masks') o.masks = resolve(value(++i, a));
    else if (a === '--phase') o.phase = value(++i, a);
    else if (a === '--strict') o.strict = true;
    else if (a === '--max-diffs') o.maxDiffs = parseInt(value(++i, a), 10);
    else if (a === '--context') o.context = parseInt(value(++i, a), 10);
    else if (a === '--write-normalized') o.writeNormalized = resolve(value(++i, a));
    else if (a === '--hash') o.hash = true;
    else if (a === '--json') o.json = true;
    else if (a === '--baseline-dir') o.baselineDir = resolve(value(++i, a));
    else if (a === '--candidate-dir') o.candidateDir = resolve(value(++i, a));
    else if (a === '--help' || a === '-h') usage();
    else if (a.startsWith('--')) usage(`unknown option ${a}`);
    else o.files.push(resolve(a));
  }
  if (Number.isNaN(o.maxDiffs) || Number.isNaN(o.context)) usage('--max-diffs and --context need a number');

  let rulesLoaded;
  try { rulesLoaded = loadRules(o); } catch (e) { usage(e.message); }

  if (o.hash) {
    if (!o.files.length) usage('--hash needs at least one file');
    let exit = 0;
    for (const f of o.files) {
      try { console.log(`${normalize(readGcode(f), rulesLoaded.rules).hash}  ${f}`); }
      catch (e) { console.error(`error: ${f}: ${e.message}`); exit = 3; }
    }
    process.exit(exit);
  }

  let results;
  if (o.baselineDir || o.candidateDir) {
    if (!o.baselineDir || !o.candidateDir || o.files.length) usage('directory mode needs --baseline-dir and --candidate-dir');
    for (const d of [o.baselineDir, o.candidateDir]) if (!existsSync(d) || !statSync(d).isDirectory()) { console.error(`error: not a directory: ${d}`); process.exit(3); }
    results = compareDirs(o.baselineDir, o.candidateDir, { ...o, rulesLoaded });
  } else {
    if (o.files.length !== 2) usage('give two files, or --baseline-dir/--candidate-dir');
    results = [compareFiles(o.files[0], o.files[1], { ...o, rulesLoaded })];
  }
  const summary = summarize(results, o);
  if (o.json) {
    console.log(JSON.stringify({ results, summary }, null, 1));
  } else {
    const nameWidth = Math.max(...results.map((r) => r.name.length), 14);
    for (const r of results) printResult(r, { nameWidth });
    console.log(`RESULT: ${summary.identical} identical, ${summary.different} different, ${summary.missing} missing, ${summary.extra} extra, ${summary.warnings} warnings${summary.error ? `, ${summary.error} errors` : ''}`);
  }
  process.exit(summary.exit);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main(process.argv.slice(2));
